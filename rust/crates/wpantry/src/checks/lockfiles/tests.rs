/// Text that isn't the lockfile it's named as is an error (so the scan
/// reports it unchecked), never a lockfile with no packages; one the tool
/// wrote with no packages still reads as empty.
#[test]
fn a_file_that_isnt_its_lockfile_is_an_error_not_empty() {
    let d = crate::utils::temp::TempDir::new("notlock").unwrap();
    for name in crate::checks::supply_chain::repos::LOCKFILES.iter().filter(|n| !requirements::is_requirements(n)) {
        for (i, text) in ["this is not a valid lockfile\n", "", "{}\n"].iter().enumerate() {
            let dir = d.path().join(format!("{i}-{name}"));
            std::fs::create_dir_all(&dir).unwrap();
            let f = dir.join(name);
            std::fs::write(&f, text).unwrap();
            assert!(matches!(extract(&f), Err(Error::Invalid(_))), "{name} accepted {text:?}");
        }
    }
    let empty = [
        ("pnpm-lock.yaml", "lockfileVersion: '9.0'\n\nimporters:\n  .: {}\n"),
        ("package-lock.json", r#"{"name": "x", "lockfileVersion": 3, "packages": {"": {}}}"#),
        ("package-lock.json", r#"{"name": "x", "version": "1.0.0", "lockfileVersion": 1}"#),
        ("Cargo.lock", "version = 4\n"),
        ("go.mod", "module example.com/x\n\ngo 1.24\n"),
        ("yarn.lock", "# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n"),
    ];
    for (i, (name, text)) in empty.into_iter().enumerate() {
        let dir = d.path().join(format!("ok{i}-{name}"));
        std::fs::create_dir_all(&dir).unwrap();
        let f = dir.join(name);
        std::fs::write(&f, text).unwrap();
        let got = extract(&f).unwrap().unwrap();
        assert!(got.iter().all(|p| p.name == "stdlib"), "{name}: {got:?}");
    }
}

#[cfg(unix)]
#[test]
fn a_lockfile_linking_outside_the_repo_is_not_read() {
    let d = crate::utils::temp::TempDir::new("linkout").unwrap();
    let (repo, outside) = (d.path().join("repo"), d.path().join("outside"));
    std::fs::create_dir_all(repo.join("sub")).unwrap();
    std::fs::create_dir_all(&outside).unwrap();
    std::fs::write(outside.join("Cargo.lock"), "version = 4\n").unwrap();
    std::os::unix::fs::symlink(outside.join("Cargo.lock"), repo.join("Cargo.lock")).unwrap();
    assert!(matches!(extract_within(&repo.join("Cargo.lock"), &repo), Err(Error::Invalid(_))));
    // A link that stays inside the repo is fine.
    std::fs::write(repo.join("sub/Cargo.lock"), "version = 4\n").unwrap();
    std::os::unix::fs::symlink(repo.join("sub/Cargo.lock"), repo.join("sub/linked.lock")).unwrap();
    std::fs::rename(repo.join("sub/linked.lock"), repo.join("Cargo.lock")).unwrap();
    assert!(extract_within(&repo.join("Cargo.lock"), &repo).unwrap().is_some());
}

#[test]
fn every_scanned_name_is_supported() {
    for name in crate::checks::supply_chain::repos::LOCKFILES {
        assert!(supported(name), "{name}");
    }
    assert!(supported("requirements-dev.txt") && supported("requirements.in.txt"));
    assert!(supported("App.csproj") && supported("Lib.fsproj") && supported("Old.vbproj"));
    assert!(!supported("requirements.in") && !supported("yarn.lock.bak"));
}

/// A .NET project file that isn't one is an error too, and its
/// not-checked references come back beside the packages.
#[test]
fn dotnet_project_files_read_through_extract() {
    let d = crate::utils::temp::TempDir::new("notproj").unwrap();
    let f = d.path().join("App.csproj");
    std::fs::write(&f, "this is not a project\n").unwrap();
    assert!(matches!(extract(&f), Err(Error::Invalid(_))));
    std::fs::write(
        &f,
        r#"<Project><ItemGroup>
  <PackageReference Include="Newtonsoft.Json" Version="12.0.1" />
  <PackageReference Include="Newtonsoft.Json" Version="12.0.1" />
  <PackageReference Include="Foo" Version="$(Undefined)" />
</ItemGroup></Project>"#,
    )
    .unwrap();
    let x = extract_noting(&f, d.path()).unwrap().unwrap();
    let (pkgs, notes) = (x.packages, x.unchecked);
    assert_eq!(pkgs, [Package::new("NuGet", "Newtonsoft.Json", "12.0.1").direct(true)]);
    assert_eq!(notes.len(), 1, "{notes:?}");
    assert_eq!(extract(&f).unwrap().unwrap(), pkgs);
}

/// What a Directory.Build.props declares comes back apart, with its path;
/// `extract` folds it into the project's packages, each once.
#[test]
fn inherited_dotnet_references_come_back_apart() {
    let d = crate::utils::temp::TempDir::new("inherited").unwrap();
    let props = d.path().join("Directory.Build.props");
    std::fs::write(
        &props,
        r#"<Project><ItemGroup><PackageReference Include="Shared" Version="1.0.0" /></ItemGroup></Project>"#,
    )
    .unwrap();
    let f = d.path().join("App.csproj");
    std::fs::write(
        &f,
        r#"<Project><ItemGroup><PackageReference Include="Own" Version="2.0.0" /></ItemGroup></Project>"#,
    )
    .unwrap();
    let x = extract_noting(&f, d.path()).unwrap().unwrap();
    let shared = Package::new("NuGet", "Shared", "1.0.0").direct(true);
    let own = Package::new("NuGet", "Own", "2.0.0").direct(true);
    assert_eq!((x.packages, x.inherited), (vec![own.clone()], vec![(props, shared.clone())]));
    assert_eq!(extract(&f).unwrap().unwrap(), [own, shared]);
}

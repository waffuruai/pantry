"""Vendor pantry-rules' secret rules into wpantry.

rust/crates/wpantry/assets/secrets/rules.yar is compiled into wpantry, so the secret scan works
offline: it is every rules/any/secret/*.yar of a pantry-rules checkout, in file-name order, under
a header naming the commit. Their test cases go to rust/crates/wpantry/tests/secret-cases.toml,
which wpantry's tests run through the scanner. Standard library only:

    python3 scripts/secret_rules.py PANTRY_RULES_CHECKOUT
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RULES = ROOT / "rust/crates/wpantry/assets/secrets/rules.yar"
CASES = ROOT / "rust/crates/wpantry/tests/secret-cases.toml"
SOURCE = "rules/any/secret"


def commit(checkout: pathlib.Path) -> str:
    """The checkout's commit, marked `-dirty` when rules/any/secret has changes not committed."""
    sha = subprocess.run(["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    dirty = subprocess.run(["git", "-C", str(checkout), "status", "--porcelain", "--", SOURCE], capture_output=True, text=True, check=True).stdout.strip()
    return sha + ("-dirty" if dirty else "")


def bundle(checkout: pathlib.Path, sha: str) -> tuple[str, str]:
    src = checkout / SOURCE
    rules = sorted(src.glob("*.yar"))
    cases = sorted(src.glob("*.test.toml"))
    if not rules:
        raise SystemExit(f"no rules in {src}")
    head = (f"// pantry-rules {sha}, {SOURCE}: {len(rules)} files. Generated by scripts/secret_rules.py;\n"
            "// change the rules in pantry-rules and vendor them again.\n")
    text = head + "".join(f"\n// ---- {f.name}\n{f.read_text()}" for f in rules)
    head = f"# pantry-rules {sha}, {SOURCE}: the cases of {len(cases)} rules. Generated by scripts/secret_rules.py.\n"
    tests = head + "".join(f"\n# ---- {f.name}\n{f.read_text()}" for f in cases)
    return text, tests


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("checkout", type=pathlib.Path, help="a pantry-rules checkout")
    args = ap.parse_args(argv)
    text, tests = bundle(args.checkout, commit(args.checkout))
    RULES.parent.mkdir(parents=True, exist_ok=True)
    RULES.write_text(text)
    CASES.write_text(tests)
    print(f"wrote {RULES.relative_to(ROOT)} and {CASES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

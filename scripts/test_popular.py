"""popular.py against faked registries:

    python3 -m unittest discover -s scripts
"""

from __future__ import annotations

import io
import json
import tarfile
import tomllib
import unittest

import popular


def tarball(js: str) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        data = js.encode()
        info = tarfile.TarInfo("package/lib/top.js")
        info.size = len(data)
        tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


TOP_JS = "export const top = [\n  'semver',\n  '@babel/core',\n  'Lodash',\n  'semver',\n  'has space',\n  'chalk',\n]\n"


def fake(url: str) -> bytes:
    if url == popular.NPM_TARBALL:
        return tarball(TOP_JS)
    if url == popular.PYPI_JSON:
        rows = [{"project": "requests", "download_count": 5}, {"project": "boto3", "download_count": 9}]
        return json.dumps({"last_update": "2026-11-01 06:41:05", "rows": rows}).encode()
    if url.startswith("https://crates.io/"):
        page = int(url.rsplit("=", 1)[1])
        crates = [{"name": "serde"}, {"name": "syn"}] if page == 1 else []
        return json.dumps({"crates": crates}).encode()
    if url.startswith("https://packages.ecosyste.ms/"):
        page = int(url.rsplit("=", 1)[1])
        return json.dumps(["rails", "rake"] if page == 1 else []).encode()
    raise AssertionError(url)


class Sources(unittest.TestCase):
    def test_npm_reads_the_list_as_data_lowercased_and_deduplicated(self):
        names, source = popular.npm(fake, 10)
        self.assertEqual(names, ["semver", "@babel/core", "lodash", "chalk"])
        self.assertIn(popular.NPM_HIGH_IMPACT, source)

    def test_count_caps_the_ranking_in_order(self):
        self.assertEqual(popular.npm(fake, 2)[0], ["semver", "@babel/core"])
        names, source = popular.pypi(fake, 1)
        self.assertEqual(names, ["boto3"], "most downloaded first")
        self.assertIn("2026-11-01", source)

    def test_paged_sources_stop_at_an_empty_page(self):
        self.assertEqual(popular.crates(fake, 5, pause=0)[0], ["serde", "syn"])
        self.assertEqual(popular.gems(fake, 5)[0], ["rails", "rake"])

    def test_names_are_registry_names(self):
        self.assertEqual(popular.clean(["A", "b-c", "d_e.f", "@s/p", "x y", "@/bad", "-lead", ""], 10), ["a", "b-c", "d_e.f", "@s/p"])


class Render(unittest.TestCase):
    def test_file_is_toml_with_a_header_per_source_and_sorted_names(self):
        lists = {
            "npm": (["semver", "@babel/core"], "npm-high-impact 1.13.0"),
            "PyPI": (["requests", "boto3"], "hugovk"),
            "crates.io": (["syn", "serde"], "crates.io API"),
            "RubyGems": (["rake", "rails"], "ecosyste.ms"),
        }
        text = popular.render(lists, "2026-11-01")
        lines = text.splitlines()
        self.assertTrue(all(l.startswith("#") for l in lines[:12]), lines[:12])
        self.assertIn("# Generated by scripts/popular.py on 2026-11-01; regenerate rather than edit.", lines)
        self.assertIn(f"# npm             2 names  npm-high-impact 1.13.0, plus {len(popular.EXTRA['npm'])} wallet libraries", lines)
        parsed = tomllib.loads(text)["popular"]
        self.assertEqual(parsed["npm"], sorted({"semver", "@babel/core", *popular.EXTRA["npm"]}))
        self.assertEqual((parsed["PyPI"], parsed["crates.io"], parsed["RubyGems"]),
                         (["boto3", "requests"], ["serde", "syn"], ["rails", "rake"]))
        self.assertTrue(text.endswith("\n"))

if __name__ == "__main__":
    unittest.main()

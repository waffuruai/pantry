//! What we know how to check: each tool's binaries, how to read its version,
//! and how OSV (and endoflife.date) know it. Data only; `tools` finds them.
//! Generated from `python/wscanner/catalog.py` and kept in step with it
//! (tests/catalog.rs compares the two while python/ exists).
//!
//! An OSV mapping is an ecosystem package, ("npm", "@openai/codex", "{v}"),
//! or an upstream repo plus its release-tag format, ("GIT", repo URL, "{v}").
//! Tag formats: {v} the version, {v3} padded to three parts (8.10 → 8.10.0),
//! {u} with dots as underscores, {ssh} OpenSSH's V_9_6_P1 style.

/// How endoflife.date names a release cycle.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Cycle {
    Major,
    Minor,
    /// Java: "1.8.0" → "8", "21.0.5" → "21".
    Java,
}

impl Cycle {
    pub fn of(self, v: &str) -> String {
        let parts: Vec<&str> = v.split('.').collect();
        match self {
            Cycle::Major => parts[0].to_string(),
            Cycle::Minor => parts[..parts.len().min(2)].join("."),
            Cycle::Java if v.starts_with("1.") => parts.get(1).copied().unwrap_or("").to_string(),
            Cycle::Java => parts[0].to_string(),
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Tool {
    pub name: &'static str,
    pub kind: &'static str,
    pub bins: &'static [&'static str],
    pub args: &'static [&'static str],
    /// A regex (multiline) whose group 1 is the version.
    pub pattern: &'static str,
    /// (ecosystem, package, tag format)
    pub osv: Option<(&'static str, &'static str, &'static str)>,
    /// (endoflife.date product, cycle)
    pub eol: Option<(&'static str, Cycle)>,
    /// Check it even when Homebrew or an app installed it (no one else does).
    pub always: bool,
    /// Where version managers keep other installs, besides PATH.
    pub paths: &'static [&'static str],
    /// How to update it, overriding the detected way; never run unattended.
    pub fix: &'static str,
}

